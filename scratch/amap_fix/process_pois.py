# Match POIs against existing
def is_existing(name):
    """Check if a POI name matches an existing kindergarten."""
    norm = normalize_name(name)
    if not norm or len(norm) < 2:
        return True  # Skip ambiguous short names
    # Direct match
    if norm in norm_existing:
        return True
    # Check if any normalized existing name is contained within or contains this one
    for en in norm_existing:
        if len(norm) >= 3 and len(en) >= 3:
            if norm in en or en in norm:
                return True
    return False

