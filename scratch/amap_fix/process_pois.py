# Name matching function - normalize names
def normalize_name(name):
    """Normalize a kindergarten name for fuzzy matching."""
    n = name.strip()
    # Remove parentheses content
    n = re.sub(r'[（(].*?[）)]', '', n)
    # Remove common prefixes/suffixes
    n = n.replace("西安市", "").replace("西安", "")
    n = re.sub(r'(新城|碑林|莲湖|雁塔|未央|灞桥|长安|临潼|高陵|鄠邑|阎良|蓝田|周至)', '', n)
    n = n.replace("区", "").replace("县", "")
    # Remove spaces and punctuation
    n = re.sub(r'[\s·\-—\.]', '', n)
    return n.strip()

